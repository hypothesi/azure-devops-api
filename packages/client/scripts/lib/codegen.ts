import type { Manifest } from '@hypothesi/azure-devops-openapi/manifest';

interface OpenAPIOperation {
   readonly 'x-ado-api-version'?: string;
   readonly parameters?: readonly { readonly name?: string; readonly in?: string; readonly required?: boolean }[];
}

// A type alias, not an interface, so it is assignable to Kubb's `Record<string, unknown>` input.
export type OpenAPIDocument = {
   readonly servers?: readonly { readonly url: string; readonly variables?: Record<string, { default: string }> }[];
   readonly paths: Record<string, Record<string, unknown>>;
};

export interface AreaModule {
   readonly area: string;
   /** The first API version of a group of identical versions, and the folder name. */
   readonly folder: string;
   readonly apiVersions: readonly string[];
}

interface AreaSpec {
   readonly module: AreaModule;
   readonly spec: OpenAPIDocument;
}

/**
 * Each operation's `[apiVersion, serverIndex]`, keyed by `METHOD urlTemplate`. An operation
 * with optional path parameters has their names as a third item.
 */
interface OperationTable {
   readonly servers: string[];
   readonly operations: Map<string, readonly [string, number] | readonly [string, number, readonly string[]]>;
}

interface PathItemContext {
   readonly area: string;
   readonly apiVersion: string;
   readonly urlTemplate: string;
   readonly serverIndex: number;
}

interface EnumNode {
   readonly namedEnumValues?: readonly { readonly value: unknown }[] | undefined;
   readonly enumValues?: readonly unknown[] | undefined;
}

export const BANNER = '// Generated by scripts/generate.ts. Do not edit.\n';

const HTTP_METHODS: ReadonlySet<string> = new Set(['get', 'put', 'post', 'delete', 'options', 'head', 'patch']),
   IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** Splits an area's API versions into runs of versions whose contract is identical. */
export function groupVersions(area: string, data: Pick<Manifest, 'areas'>, versions: readonly string[]): AreaModule[] {
   const areaVersions = data.areas[area]?.versions ?? {};

   return versions.reduce<AreaModule[]>((memo, apiVersion, index) => {
      const entry = areaVersions[apiVersion],
         previous = memo.at(-1),
         isIdentical =
            entry?.comparedToPrevious?.change === 'identical' &&
            entry.comparedToPrevious.apiVersion === versions[index - 1] &&
            previous?.apiVersions.at(-1) === versions[index - 1];

      if (!entry) {
         return memo;
      }

      if (!IDENTIFIER.test(area)) {
         throw new Error(`Area ${area} is not a valid JavaScript identifier`);
      }

      if (isIdentical && previous) {
         return [...memo.slice(0, -1), { ...previous, apiVersions: [...previous.apiVersions, apiVersion] }];
      }

      return [...memo, { area, folder: apiVersion, apiVersions: [apiVersion] }];
   }, []);
}

function isString(value: unknown): value is string {
   return typeof value === 'string';
}

/** Whether every value of a Kubb enum node is a string. */
export function isStringEnum(node: EnumNode): boolean {
   const values =
      node.namedEnumValues?.map((member) => {
         return member.value;
      }) ??
      node.enumValues ??
      [];

   return values.every(isString);
}

/** The server URL with every variable except `{organization}` replaced by its default. */
export function getServerURL(servers: OpenAPIDocument['servers']): string {
   const server = servers?.[0];

   if (!server) {
      return '{organization}';
   }

   return Object.entries(server.variables ?? {}).reduce((url, [name, variable]) => {
      return name === 'organization' ? url : url.replaceAll(`{${name}}`, variable.default);
   }, server.url);
}

function isServerList(value: unknown): value is OpenAPIDocument['servers'] {
   return (
      Array.isArray(value) &&
      value.every((server) => {
         return typeof server === 'object' && server !== null && 'url' in server && typeof server.url === 'string';
      })
   );
}

function isOperation(value: unknown): value is OpenAPIOperation {
   return typeof value === 'object' && value !== null;
}

/** The index of `serverURL` in `servers`. Adds it to the end when it is not there. */
function getServerIndex(servers: string[], serverURL: string): number {
   const index = servers.indexOf(serverURL);

   return index === -1 ? servers.push(serverURL) - 1 : index;
}

function addOperation(table: OperationTable, key: string, operation: OpenAPIOperation, context: PathItemContext): void {
   const operationVersion = operation['x-ado-api-version'],
      existing = table.operations.get(key);

   if (operationVersion === undefined) {
      throw new Error(`${context.area} ${context.apiVersion}: ${key} has no x-ado-api-version`);
   }

   if (existing && (existing[0] !== operationVersion || existing[1] !== context.serverIndex)) {
      throw new Error(`${context.apiVersion}: ${key} is in two areas with different API versions or servers`);
   }

   const optionalPath = (operation.parameters ?? [])
      .filter((parameter) => {
         return parameter.in === 'path' && parameter.required === false;
      })
      .map((parameter) => {
         return String(parameter.name);
      });

   table.operations.set(
      key,
      optionalPath.length > 0
         ? [operationVersion, context.serverIndex, optionalPath]
         : [operationVersion, context.serverIndex],
   );
}

function addPathItem(table: OperationTable, pathItem: Record<string, unknown>, context: PathItemContext): void {
   for (const [method, operation] of Object.entries(pathItem)) {
      if (HTTP_METHODS.has(method) && isOperation(operation)) {
         addOperation(table, `${method.toUpperCase()} ${context.urlTemplate}`, operation, context);
      }
   }
}

/**
 * Lists the API version and server of every operation of an API version. Throws when an
 * operation has no `x-ado-api-version`, or when two areas define one operation differently.
 */
export function buildOperationTable(apiVersion: string, specs: readonly AreaSpec[]): OperationTable {
   const table: OperationTable = { servers: [], operations: new Map() };

   for (const { module, spec } of specs) {
      for (const [urlTemplate, pathItem] of Object.entries(spec.paths)) {
         // An area built from files with different hosts has `servers` on the path items of the other hosts.
         const serverURL = getServerURL(isServerList(pathItem.servers) ? pathItem.servers : spec.servers);

         addPathItem(table, pathItem, {
            area: module.area,
            apiVersion,
            urlTemplate,
            serverIndex: getServerIndex(table.servers, serverURL),
         });
      }
   }

   return table;
}

/** The source of `{apiVersion}/index.ts`, with one namespace per area. */
export function getVersionIndexSource(modules: readonly AreaModule[]): string {
   return (
      BANNER +
      modules
         .map((module) => {
            return `export * as ${module.area} from '../${module.area}/${module.folder}/index';\n`;
         })
         .join('')
   );
}

/** The source of `{apiVersion}/operations.ts`, with the operations sorted by key. */
export function getOperationsSource(apiVersion: string, table: OperationTable): string {
   return (
      `${BANNER}import type { OperationTable } from '../../core/context';\n\n` +
      `export const operations: OperationTable = {\n` +
      `   apiVersion: ${JSON.stringify(apiVersion)},\n` +
      `   servers: ${JSON.stringify(table.servers)},\n` +
      `   operations: {\n` +
      [...table.operations]
         .toSorted(([a], [b]) => {
            return a.localeCompare(b);
         })
         .map(([key, value]) => {
            return `      ${JSON.stringify(key)}: ${JSON.stringify(value)},\n`;
         })
         .join('') +
      `   },\n};\n`
   );
}

/** Reads the `version` of a parsed package.json. Throws when it is missing or not a string. */
export function parseClientVersion(packageJSON: unknown): string {
   const version =
      typeof packageJSON === 'object' && packageJSON !== null && 'version' in packageJSON
         ? packageJSON.version
         : undefined;

   if (typeof version !== 'string' || version === '') {
      throw new Error('packages/client/package.json has no version');
   }

   return version;
}
